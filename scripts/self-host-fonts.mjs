/**
 * Downloads Manrope and DM Serif Display from Google Fonts as WOFF2
 * files and generates @font-face CSS for self-hosting.
 *
 * Only downloads the latin subset (U+0000-00FF) which covers all
 * characters needed for this English-language site.
 *
 * Usage: node scripts/self-host-fonts.mjs
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fontsDir = join(root, "public", "fonts");
mkdirSync(fontsDir, { recursive: true });

const CSS_URLS = [
  "https://fonts.googleapis.com/css2?family=Manrope:wght@400;500;600;700;800&display=swap",
  "https://fonts.googleapis.com/css2?family=DM+Serif+Display:ital@0;1&display=swap",
];

const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36";

let css = "/* Self-hosted fonts — generated by scripts/self-host-fonts.mjs */\n\n";

for (const cssUrl of CSS_URLS) {
  const res = await fetch(cssUrl, { headers: { "User-Agent": UA } });
  const cssText = await res.text();

  /* Split into @font-face blocks */
  const blocks = cssText.split("@font-face").slice(1);
  for (const block of blocks) {
    const familyMatch = block.match(/font-family:\s*'([^']+)'/);
    const styleMatch = block.match(/font-style:\s*(\w+)/);
    const weightMatch = block.match(/font-weight:\s*(\d+)/);
    const urlMatch = block.match(/url\(([^)]+)\)/);
    const rangeMatch = block.match(/unicode-range:\s*([^;]+)/);

    if (!familyMatch || !weightMatch || !urlMatch) continue;

    const family = familyMatch[1];
    const style = styleMatch?.[1] ?? "normal";
    const weight = weightMatch[1];
    const woff2Url = urlMatch[1];
    const unicodeRange = rangeMatch?.[1]?.trim() ?? "";

    if (!woff2Url.endsWith(".woff2")) continue;

    /* Only download latin subset */
    if (unicodeRange && !unicodeRange.includes("U+0000-00FF") && !unicodeRange.includes("U+0000-00FF,")) {
      continue;
    }

    const fileName = `${family.toLowerCase().replace(/\s+/g, "-")}-${weight}-${style}.woff2`;
    const filePath = join(fontsDir, fileName);

    try {
      const fontRes = await fetch(woff2Url);
      if (!fontRes.ok) throw new Error(`HTTP ${fontRes.status}`);
      const buf = Buffer.from(await fontRes.arrayBuffer());
      writeFileSync(filePath, buf);
      console.log(`ok ${fileName} (${(buf.length / 1024).toFixed(1)} KB)`);

      css += `@font-face {
  font-family: "${family}";
  font-style: ${style};
  font-weight: ${weight};
  font-display: swap;
  src: url("/fonts/${fileName}") format("woff2");
}

`;
    } catch (err) {
      console.error(`FAIL ${fileName}: ${err.message}`);
    }
  }
}

writeFileSync(join(root, "src", "fonts.css"), css);
console.log(`\nGenerated src/fonts.css`);
